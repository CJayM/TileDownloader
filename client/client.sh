#!/bin/sh
# ============================================================
#  Tile Downloader — клиент (отдельный проект)
#  Получает задачи с сервера, скачивает тайлы, сдаёт их.
#  Запуск:  ./client.sh [дополнительные аргументы]
#  Адрес сервера: ./client.sh --server http://<host>:31059
#  Несколько клиентов: несколько процессов (каждый под своим
#  --client-id) на разных машинах или на одной.
#  Зависимости: pip install -r requirements.txt
# ============================================================
cd "$(dirname "$0")" || exit 1
python3 client.py --server http://127.0.0.1:31059 --client-id "$(hostname)" --threads 16 "$@"
