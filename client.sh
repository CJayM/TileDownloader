#!/bin/sh
# ============================================================
#  Tile Downloader — клиент
#  Получает задачи с сервера, скачивает тайлы, сдаёт их.
#  Запуск:  ./client.sh [дополнительные аргументы]
#  Несколько клиентов: запустите несколько процессов (каждый
#  под своим --client-id) на разных машинах или на одной.
# ============================================================
python3 client.py --server http://127.0.0.1:8080 --client-id "$(hostname)" --threads 16 "$@"
